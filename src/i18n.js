export function normalizeLocale(value) {
  const locale = String(value || '').toLowerCase().split('-')[0];
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function loadLocale(storage = globalThis.localStorage) {
  try { return normalizeLocale(storage?.getItem(LOCALE_STORAGE_KEY)); }
  catch { return DEFAULT_LOCALE; }
}

export function saveLocale(locale, storage = globalThis.localStorage) {
  const normalized = normalizeLocale(locale);
  try { storage?.setItem(LOCALE_STORAGE_KEY, normalized); } catch {}
  return normalized;
}

export function translate(locale, key, values = {}) {
  const normalized = normalizeLocale(locale);
  const template = messages[normalized][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function translator(locale) {
  return (key, values) => translate(locale, key, values);
}
